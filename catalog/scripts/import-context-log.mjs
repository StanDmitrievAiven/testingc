// Snapshots the local mcpproxy purpose log into src/data/context-log.ts, the same way the rest of
// the catalog is a captured snapshot. Run `npm run context:import` after the proxy records changes.
//
//   node scripts/import-context-log.mjs [--project name] [--store ~/.mcpproxy]
//   node scripts/import-context-log.mjs --check   # self-check, touches no files
import { readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import path from 'node:path'
import assert from 'node:assert/strict'

const DEFAULT_PROJECT = 'data-innovation-summit'
const OUT = path.join(import.meta.dirname, '..', 'src', 'data', 'context-log.ts')

/**
 * context.jsonl is an append log: a row is written when the call is gated (`pending`) and again
 * when it finishes, both under the same `id`. Later lines therefore supersede earlier ones, and
 * only service mutations in this project belong in the catalog.
 */
export function normalize(rows, project) {
  const byId = new Map()
  for (const row of rows) {
    if (row.resourceType !== 'service' || row.project !== project) continue
    byId.set(row.id, {
      id: row.id,
      serviceId: row.serviceName,
      version: row.version,
      operation: row.operation,
      toolName: row.toolName,
      purpose: row.purpose,
      status: row.status,
      createdAt: row.createdAt,
      ...(row.durationMs == null ? {} : { durationMs: row.durationMs }),
      ...(row.errorText ? { errorText: row.errorText } : {}),
      clientName: row.clientName,
    })
  }
  return [...byId.values()].sort((a, b) => a.id - b.id)
}

function readJsonl(file) {
  return readFileSync(file, 'utf8')
    .split('\n')
    .filter((line) => line.trim())
    .map((line) => JSON.parse(line))
}

function check() {
  const rows = [
    { id: 2, resourceType: 'service', project: 'p', serviceName: 'b', version: 1, operation: 'deploy', toolName: 't', purpose: 'second', status: 'pending', createdAt: 'B', clientName: 'c', durationMs: null },
    { id: 1, resourceType: 'service', project: 'p', serviceName: 'a', version: 1, operation: 'create', toolName: 't', purpose: 'first', status: 'pending', createdAt: 'A', clientName: 'c', durationMs: null },
    { id: 1, resourceType: 'service', project: 'p', serviceName: 'a', version: 1, operation: 'create', toolName: 't', purpose: 'first', status: 'ok', createdAt: 'A', clientName: 'c', durationMs: 42 },
    { id: 3, resourceType: 'service', project: 'other', serviceName: 'x', version: 1, operation: 'create', toolName: 't', purpose: 'elsewhere', status: 'ok', createdAt: 'C', clientName: 'c' },
    { id: 4, resourceType: 'topic', project: 'p', serviceName: 'a', version: 1, operation: 'create', toolName: 't', purpose: 'not a service', status: 'ok', createdAt: 'D', clientName: 'c' },
  ]
  const out = normalize(rows, 'p')

  assert.deepEqual(out.map((row) => row.id), [1, 2], 'other projects and non-services are dropped, output is ordered by id')
  assert.equal(out[0].status, 'ok', 'the finalised row supersedes the pending row with the same id')
  assert.equal(out[0].durationMs, 42)
  assert.ok(!('durationMs' in out[1]), 'a null duration is omitted rather than serialised')
  assert.ok(!('errorText' in out[0]), 'absent error text is omitted')
  console.log('import-context-log: checks passed')
}

function main() {
  const args = process.argv.slice(2)
  if (args.includes('--check')) return check()

  const project = args[args.indexOf('--project') + 1] || DEFAULT_PROJECT
  const storeDir = (args.includes('--store') ? args[args.indexOf('--store') + 1] : '~/.mcpproxy').replace(/^~/, homedir())
  const source = path.join(storeDir, 'context.jsonl')

  const changes = normalize(readJsonl(source), project)
  // Purposes are prose with apostrophes and quotes in them, so the records stay JSON-quoted
  // rather than being rewritten to the repo's single-quote style.
  writeFileSync(
    OUT,
    `// Generated by scripts/import-context-log.mjs from ${source.replace(homedir(), '~')} — do not edit.
// The local mcpproxy gates every mutating Aiven MCP call behind a written purpose; this is the
// captured log for project ${project}. The Changes tab prefers live data when the proxy is running.
import type { ContextChange } from '@/types'

export const contextLogCapturedAt = '${new Date().toISOString()}'

export const contextLog: ContextChange[] = ${JSON.stringify(changes, null, 2)}
`,
  )
  console.log(`wrote ${changes.length} changes for ${new Set(changes.map((c) => c.serviceId)).size} services to ${path.relative(process.cwd(), OUT)}`)
}

main()
